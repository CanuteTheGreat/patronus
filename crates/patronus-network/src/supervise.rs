//! Supervision of the per-interface daemons lane C runs (DHCP clients,
//! pppd), through the init system when there is one:
//!
//! - systemd: template units `patronus-dhcpc@<dev>.service` /
//!   `patronus-pppoe@<link>.service` (shipped in gentoo/.../files),
//! - OpenRC: multiplexed scripts `/etc/init.d/patronus-dhcpc.<dev>` ->
//!   `patronus-dhcpc` (the symlink is created on demand),
//! - no init system (containers, netlab): the daemon is started directly,
//!   detached, with a pidfile under the run dir.
//!
//! In every mode the command line lives in
//! `<state>/svc/<service>.<instance>.env` (`PATRONUS_CMD=...`), which the
//! units/scripts read, so the store stays the only source of truth and an
//! instance is restarted exactly when its command line or config changed.

use patronus_core::service::{InitSystem, ServiceManager};
use patronus_core::{Error, Result};
use std::path::{Path, PathBuf};

/// Default state dir for generated daemon configs (writable by
/// patronus-web: it is under /var/lib/patronus).
pub const DEFAULT_STATE_DIR: &str = "/var/lib/patronus/net";
pub const DEFAULT_RUN_DIR: &str = "/run/patronus";

/// Where generated files and pidfiles go.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NetPaths {
    pub state_dir: PathBuf,
    pub run_dir: PathBuf,
}

impl Default for NetPaths {
    fn default() -> Self {
        Self {
            state_dir: std::env::var_os("PATRONUS_NET_DIR")
                .map(PathBuf::from)
                .unwrap_or_else(|| PathBuf::from(DEFAULT_STATE_DIR)),
            run_dir: std::env::var_os("PATRONUS_RUN_DIR")
                .map(PathBuf::from)
                .unwrap_or_else(|| PathBuf::from(DEFAULT_RUN_DIR)),
        }
    }
}

impl NetPaths {
    pub fn under(dir: &Path) -> Self {
        Self {
            state_dir: dir.join("net"),
            run_dir: dir.join("run"),
        }
    }
    fn env_file(&self, service: &str, inst: &str) -> PathBuf {
        self.state_dir
            .join("svc")
            .join(format!("{service}.{inst}.env"))
    }
    fn pidfile(&self, service: &str, inst: &str) -> PathBuf {
        self.run_dir.join(format!("{service}.{inst}.pid"))
    }
    fn logfile(&self, service: &str, inst: &str) -> PathBuf {
        self.run_dir.join(format!("{service}.{inst}.log"))
    }
}

/// How daemons are run.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InitMode {
    Systemd,
    OpenRc,
    Direct,
}

impl InitMode {
    /// `$PATRONUS_INIT` (systemd|openrc|direct) or the running init system.
    pub fn detect() -> Self {
        match std::env::var("PATRONUS_INIT").as_deref() {
            Ok("systemd") => return InitMode::Systemd,
            Ok("openrc") => return InitMode::OpenRc,
            Ok("direct") => return InitMode::Direct,
            _ => {}
        }
        if Path::new("/run/systemd/system").exists() {
            InitMode::Systemd
        } else if Path::new("/run/openrc/softlevel").exists() {
            InitMode::OpenRc
        } else {
            InitMode::Direct
        }
    }
}

/// A daemon instance to keep running.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DaemonSpec {
    /// `patronus-dhcpc` or `patronus-pppoe`.
    pub service: &'static str,
    /// Device / link name.
    pub instance: String,
    /// Foreground command line (no shell; safe tokens only).
    pub argv: Vec<String>,
    /// Generated files the daemon reads: (path, content, mode).
    pub files: Vec<(PathBuf, String, u32)>,
}

impl DaemonSpec {
    fn env_content(&self) -> String {
        let mut h = std::collections::hash_map::DefaultHasher::new();
        use std::hash::{Hash, Hasher};
        self.argv.hash(&mut h);
        for (p, c, m) in &self.files {
            p.hash(&mut h);
            c.hash(&mut h);
            m.hash(&mut h);
        }
        format!(
            "# Generated by Patronus (interfaces applier); do not edit.\n\
             # fingerprint {:016x}\n\
             PATRONUS_CMD=\"{}\"\n",
            h.finish(),
            self.argv.join(" ")
        )
    }

    /// Human-readable line for `patronus apply --dry-run`.
    pub fn describe(&self) -> String {
        format!(
            "{}[{}]: {}",
            self.service,
            self.instance,
            self.argv.join(" ")
        )
    }
}

/// Starts/stops [`DaemonSpec`]s.
#[derive(Debug, Clone)]
pub struct Supervisor {
    pub mode: InitMode,
    pub paths: NetPaths,
}

fn io(what: impl std::fmt::Display) -> impl FnOnce(std::io::Error) -> Error {
    move |e| Error::Network(format!("{what}: {e}"))
}

/// Write `content` to `path` atomically with `mode` (temp file + rename).
pub fn write_atomic(path: &Path, content: &str, mode: u32) -> Result<bool> {
    use std::os::unix::fs::PermissionsExt;
    if let Ok(old) = std::fs::read_to_string(path) {
        let same_mode = std::fs::metadata(path)
            .map(|m| m.permissions().mode() & 0o7777 == mode)
            .unwrap_or(false);
        if old == content && same_mode {
            return Ok(false);
        }
    }
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d).map_err(io(d.display()))?;
    }
    let tmp = path.with_extension("tmp-patronus");
    std::fs::write(&tmp, content).map_err(io(tmp.display()))?;
    std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(mode))
        .map_err(io(tmp.display()))?;
    std::fs::rename(&tmp, path).map_err(io(path.display()))?;
    Ok(true)
}

fn pid_alive(pid: i32, argv0: Option<&str>) -> bool {
    // /proc/<pid>/comm, not cmdline: daemons like dhcpcd rewrite their
    // argv ("dhcpcd: rtr-wan [ip4]"), the kernel's comm stays the binary.
    let Ok(comm) = std::fs::read_to_string(format!("/proc/{pid}/comm")) else {
        return false;
    };
    // zombie?
    if let Ok(st) = std::fs::read_to_string(format!("/proc/{pid}/stat")) {
        if st
            .rsplit_once(')')
            .map(|(_, r)| r.trim_start().starts_with('Z'))
            .unwrap_or(false)
        {
            return false;
        }
    }
    match argv0 {
        None => true,
        Some(a) => {
            let full = a.rsplit('/').next().unwrap_or(a);
            let base: String = full.chars().take(15).collect();
            // some daemons rename their threads (Suricata's main thread is
            // "Suricata-Main"): the executable is the reliable identity then
            comm.trim_end() == base
                // an interpreted script (a plugin's `#!/usr/bin/env python3`)
                // runs as its interpreter: its path is then an argument
                || std::fs::read(format!("/proc/{pid}/cmdline"))
                    .map(|c| c.split(|b| *b == 0).any(|w| w == a.as_bytes()))
                    .unwrap_or(false)
                || std::fs::read_link(format!("/proc/{pid}/exe"))
                    .ok()
                    .and_then(|p| p.file_name().map(|n| n.to_string_lossy().into_owned()))
                    .is_some_and(|n| n == full)
        }
    }
}

impl Supervisor {
    pub fn new(mode: InitMode, paths: NetPaths) -> Self {
        Self { mode, paths }
    }

    pub fn detect() -> Self {
        Self::new(InitMode::detect(), NetPaths::default())
    }

    fn unit(service: &str, inst: &str) -> String {
        format!("{service}@{inst}.service")
    }

    fn rc_name(service: &str, inst: &str) -> String {
        format!("{service}.{inst}")
    }

    fn sm(&self) -> ServiceManager {
        ServiceManager::with_init_system(match self.mode {
            InitMode::Systemd => InitSystem::Systemd,
            _ => InitSystem::OpenRC,
        })
    }

    fn read_pid(&self, service: &str, inst: &str) -> Option<i32> {
        std::fs::read_to_string(self.paths.pidfile(service, inst))
            .ok()
            .and_then(|s| s.trim().parse().ok())
    }

    /// Is the instance running?
    pub fn is_running(&self, service: &str, inst: &str) -> bool {
        match self.mode {
            InitMode::Systemd => std::process::Command::new("systemctl")
                .args(["is-active", "--quiet", &Self::unit(service, inst)])
                .status()
                .map(|s| s.success())
                .unwrap_or(false),
            InitMode::OpenRc => std::process::Command::new("rc-service")
                .args([&Self::rc_name(service, inst), "status"])
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .status()
                .map(|s| s.success())
                .unwrap_or(false),
            InitMode::Direct => {
                let argv0 = self.recorded_argv0(service, inst);
                self.read_pid(service, inst)
                    .map(|p| pid_alive(p, argv0.as_deref()))
                    .unwrap_or(false)
            }
        }
    }

    fn recorded_argv0(&self, service: &str, inst: &str) -> Option<String> {
        let env = std::fs::read_to_string(self.paths.env_file(service, inst)).ok()?;
        env.lines()
            .find_map(|l| l.strip_prefix("PATRONUS_CMD=\""))
            .and_then(|c| c.split_whitespace().next())
            .map(str::to_string)
    }

    /// Instances of `service` Patronus started (have an env file).
    pub fn instances(&self, service: &str) -> Vec<String> {
        let dir = self.paths.state_dir.join("svc");
        let prefix = format!("{service}.");
        let mut v: Vec<String> = std::fs::read_dir(dir)
            .map(|d| {
                d.filter_map(|e| e.ok())
                    .filter_map(|e| {
                        let n = e.file_name().to_string_lossy().to_string();
                        n.strip_prefix(&prefix)
                            .and_then(|r| r.strip_suffix(".env"))
                            .map(str::to_string)
                    })
                    .collect()
            })
            .unwrap_or_default();
        v.sort();
        v
    }

    /// Would [`ensure`](Self::ensure) leave `spec` alone (same config,
    /// already running)? Used by `--dry-run`.
    pub fn up_to_date(&self, spec: &DaemonSpec) -> bool {
        let same = |p: &Path, c: &str| std::fs::read_to_string(p).is_ok_and(|old| old == c);
        spec.files.iter().all(|(p, c, _)| same(p, c))
            && same(
                &self.paths.env_file(spec.service, &spec.instance),
                &spec.env_content(),
            )
            && self.is_running(spec.service, &spec.instance)
    }

    /// Make sure `spec` runs with exactly this command line + config.
    /// Returns true if it was (re)started.
    pub async fn ensure(&self, spec: &DaemonSpec) -> Result<bool> {
        if self.up_to_date(spec) {
            return Ok(false);
        }
        if self.mode == InitMode::Direct {
            // stop the old instance while its env file still names its
            // binary (the pid check compares it)
            self.stop_direct(spec.service, &spec.instance).await;
        }
        for (p, c, m) in &spec.files {
            write_atomic(p, c, *m)?;
        }
        let env = self.paths.env_file(spec.service, &spec.instance);
        write_atomic(&env, &spec.env_content(), 0o600)?;
        match self.mode {
            InitMode::Systemd => {
                self.sm()
                    .restart(&Self::unit(spec.service, &spec.instance))?;
            }
            InitMode::OpenRc => {
                let link =
                    PathBuf::from("/etc/init.d").join(Self::rc_name(spec.service, &spec.instance));
                if !link.exists() {
                    std::os::unix::fs::symlink(spec.service, &link).map_err(io(link.display()))?;
                }
                self.sm()
                    .restart(&Self::rc_name(spec.service, &spec.instance))?;
            }
            InitMode::Direct => self.start_direct(spec).await?,
        }
        Ok(true)
    }

    async fn start_direct(&self, spec: &DaemonSpec) -> Result<()> {
        std::fs::create_dir_all(&self.paths.run_dir).map_err(io(self.paths.run_dir.display()))?;
        let log = self.paths.logfile(spec.service, &spec.instance);
        // Detach through a shell that exits at once: the daemon is
        // reparented to init, so a long-running caller (patronus-web) never
        // accumulates zombies, and `patronus apply` can exit.
        let out = tokio::process::Command::new("/bin/sh")
            .arg("-c")
            .arg("log=\"$1\"; shift; \"$@\" </dev/null >>\"$log\" 2>&1 & echo $!")
            .arg("sh")
            .arg(&log)
            .args(&spec.argv)
            .output()
            .await
            .map_err(io("spawn"))?;
        let pid: i32 = String::from_utf8_lossy(&out.stdout)
            .trim()
            .parse()
            .map_err(|_| Error::Network(format!("could not start {}", spec.describe())))?;
        write_atomic(
            &self.paths.pidfile(spec.service, &spec.instance),
            &format!("{pid}\n"),
            0o644,
        )?;
        // fail fast if it dies immediately (bad option, missing plugin)
        tokio::time::sleep(std::time::Duration::from_millis(300)).await;
        if !pid_alive(pid, spec.argv.first().map(String::as_str)) {
            let tail = std::fs::read_to_string(&log).unwrap_or_default();
            let tail: Vec<&str> = tail.lines().rev().take(5).collect();
            return Err(Error::Network(format!(
                "{} exited at once: {}",
                spec.describe(),
                tail.into_iter().rev().collect::<Vec<_>>().join(" | ")
            )));
        }
        Ok(())
    }

    async fn stop_direct(&self, service: &str, inst: &str) -> bool {
        let Some(pid) = self.read_pid(service, inst) else {
            return false;
        };
        let argv0 = self.recorded_argv0(service, inst);
        if !pid_alive(pid, argv0.as_deref()) {
            let _ = std::fs::remove_file(self.paths.pidfile(service, inst));
            return false;
        }
        let p = nix::unistd::Pid::from_raw(pid);
        let _ = nix::sys::signal::kill(p, nix::sys::signal::Signal::SIGTERM);
        for _ in 0..30 {
            tokio::time::sleep(std::time::Duration::from_millis(100)).await;
            if !pid_alive(pid, argv0.as_deref()) {
                break;
            }
        }
        if pid_alive(pid, argv0.as_deref()) {
            let _ = nix::sys::signal::kill(p, nix::sys::signal::Signal::SIGKILL);
        }
        let _ = std::fs::remove_file(self.paths.pidfile(service, inst));
        true
    }

    /// Stop an instance and forget it. Returns true if it was running.
    pub async fn stop(&self, service: &str, inst: &str) -> Result<bool> {
        let was = self.is_running(service, inst);
        match self.mode {
            InitMode::Systemd => {
                if was {
                    self.sm().stop(&Self::unit(service, inst))?;
                }
            }
            InitMode::OpenRc => {
                if was {
                    self.sm().stop(&Self::rc_name(service, inst))?;
                }
                let link = PathBuf::from("/etc/init.d").join(Self::rc_name(service, inst));
                let _ = std::fs::remove_file(link);
            }
            InitMode::Direct => {
                self.stop_direct(service, inst).await;
            }
        }
        let _ = std::fs::remove_file(self.paths.env_file(service, inst));
        Ok(was)
    }
}

/// Find an executable in $PATH or the usual sbin directories.
pub fn which(prog: &str) -> Option<PathBuf> {
    let path = std::env::var("PATH").unwrap_or_default();
    let dirs: Vec<&str> = path
        .split(':')
        .chain(["/sbin", "/usr/sbin", "/bin", "/usr/bin"])
        .filter(|d| !d.is_empty())
        .collect();
    dirs.into_iter().map(|d| Path::new(d).join(prog)).find(|p| {
        use std::os::unix::fs::PermissionsExt;
        std::fs::metadata(p)
            .map(|m| m.is_file() && m.permissions().mode() & 0o111 != 0)
            .unwrap_or(false)
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn direct_mode_starts_restarts_on_change_and_stops() {
        let d = tempfile::tempdir().unwrap();
        let sup = Supervisor::new(InitMode::Direct, NetPaths::under(d.path()));
        let sleep = which("sleep").unwrap().to_string_lossy().to_string();
        let mut spec = DaemonSpec {
            service: "patronus-test",
            instance: "eth0".into(),
            argv: vec![sleep.clone(), "30".into()],
            files: vec![(d.path().join("net/x.conf"), "a\n".into(), 0o600)],
        };
        assert!(sup.ensure(&spec).await.unwrap());
        assert!(sup.is_running("patronus-test", "eth0"));
        let pid1 = sup.read_pid("patronus-test", "eth0").unwrap();
        // unchanged: no restart
        assert!(!sup.ensure(&spec).await.unwrap());
        assert_eq!(sup.read_pid("patronus-test", "eth0").unwrap(), pid1);
        // config change: restart
        spec.files[0].1 = "b\n".into();
        assert!(sup.ensure(&spec).await.unwrap());
        let pid2 = sup.read_pid("patronus-test", "eth0").unwrap();
        assert_ne!(pid1, pid2);
        assert!(!pid_alive(pid1, Some(&sleep)));
        assert_eq!(sup.instances("patronus-test"), vec!["eth0"]);
        // switching the binary (udhcpc -> dhcpcd) must stop the old one
        let tail = which("tail").unwrap().to_string_lossy().to_string();
        spec.argv = vec![tail.clone(), "-f".into(), "/dev/null".into()];
        assert!(sup.ensure(&spec).await.unwrap());
        assert!(!pid_alive(pid2, Some(&sleep)), "old binary still running");
        let pid3 = sup.read_pid("patronus-test", "eth0").unwrap();
        assert!(sup.stop("patronus-test", "eth0").await.unwrap());
        assert!(!pid_alive(pid3, Some(&tail)));
        assert!(sup.instances("patronus-test").is_empty());
    }

    #[tokio::test]
    async fn a_daemon_that_dies_at_once_is_an_error() {
        let d = tempfile::tempdir().unwrap();
        let sup = Supervisor::new(InitMode::Direct, NetPaths::under(d.path()));
        let spec = DaemonSpec {
            service: "patronus-test",
            instance: "x".into(),
            argv: vec![
                which("sh").unwrap().to_string_lossy().to_string(),
                "-c".into(),
                "echo nope-bad-option; exit 3".into(),
            ],
            files: vec![],
        };
        let e = sup.ensure(&spec).await.unwrap_err().to_string();
        assert!(e.contains("nope-bad-option"), "{e}");
    }
}
