    /// A radio with scripted conditions: per-channel busy percent, neighbours, CSA support.
    struct FakeIw {
        busy: Mutex<BTreeMap<i64, u64>>,
        neigh: Mutex<Vec<(String, i64, i64)>>,
        channel: Mutex<i64>,
        csa: Mutex<bool>,
        switches: Mutex<Vec<String>>,
        calls: Mutex<u64>,
        /// when set, every survey swaps `busy` with this map (two channels that trade places within the noise)
        flip: Mutex<Option<BTreeMap<i64, u64>>>,
        /// `iw phy info` text instead of the plain 2.4 GHz channel list
        phy: Mutex<Option<String>>,
        /// countries `reg_set` was called with
        regs: Mutex<Vec<String>>,
        /// interfaces whose `hostapd_status` reports DISABLED (a link that did not come up)
        down: Mutex<Vec<String>>,
    }
    impl Default for FakeIw {
        fn default() -> Self {
            Self {
                // channel 1 busy, 6 half busy and with two neighbours, 11 the quietest
                busy: Mutex::new([(1, 70), (6, 40), (11, 20)].into_iter().collect()),
                neigh: Mutex::new(vec![
                    ("aa:00:00:00:00:01".into(), 6, -50),
                    ("aa:00:00:00:00:02".into(), 6, -60),
                ]),
                channel: Mutex::new(0),
                csa: Mutex::new(true),
                switches: Mutex::new(vec![]),
                calls: Mutex::new(0),
                flip: Mutex::new(None),
                phy: Mutex::new(None),
                regs: Mutex::new(vec![]),
                down: Mutex::new(vec![]),
            }
        }
    }
    impl Iw for FakeIw {
        fn scan(&self, _: &str, _: &[i64], _: i64, _: bool) -> Result<String> {
            Ok(self
                .neigh
                .lock()
                .unwrap()
                .iter()
                .map(|(m, c, s)| {
                    format!(
                        "BSS {m}(on wlan0)\n\tfreq: {}.0\n\tsignal: {s}.00 dBm\n",
                        2407 + c * 5
                    )
                })
                .collect())
        }
        fn survey(&self, _: &str) -> Result<String> {
            let cur = *self.channel.lock().unwrap();
            if let Some(alt) = self.flip.lock().unwrap().as_mut() {
                std::mem::swap(&mut *self.busy.lock().unwrap(), alt);
            }
            // the counters of a real survey only grow: the channel in use keeps counting
            let n = {
                let mut c = self.calls.lock().unwrap();
                *c += 1;
                *c
            };
            Ok(self
                .busy
                .lock()
                .unwrap()
                .iter()
                .map(|(c, b)| {
                    let k = if *c == cur { n } else { 1 };
                    format!(
                        "Survey data from wlan0\n\tfrequency:\t{} MHz{}\n\tchannel active time:\t{} ms\n\tchannel busy time:\t{} ms\n",
                        2407 + c * 5,
                        if *c == cur { " [in use]" } else { "" },
                        100 * k,
                        b * k
                    )
                })
                .collect())
        }
        fn stations(&self, _: &str) -> Result<String> {
            Ok(String::new())
        }
        fn phy_info(&self, _: &str) -> Result<String> {
            if let Some(p) = self.phy.lock().unwrap().clone() {
                return Ok(p);
            }
            let mut o: String = (1..=13)
                .map(|c| format!("\t\t\t* {} MHz [{c}] (20.0 dBm)\n", 2407 + c * 5))
                .collect();
            if *self.csa.lock().unwrap() {
                o.push_str("\t\t * channel_switch\n");
            }
            Ok(o)
        }
        fn mac_of(&self, i: &str) -> Option<String> {
            (i == "wlan0").then(|| "02:00:00:00:00:00".to_string())
        }
        fn hostapd_status(&self, i: &str) -> Result<String> {
            let st = if self.down.lock().unwrap().iter().any(|d| d == i) {
                "DISABLED"
            } else {
                "ENABLED"
            };
            Ok(format!(
                "state={st}\nchannel={}\n",
                self.channel.lock().unwrap()
            ))
        }
        fn reg_set(&self, c: &str) -> Result<()> {
            self.regs.lock().unwrap().push(c.to_string());
            Ok(())
        }
        fn chan_switch(&self, _: &str, count: i64, freq: i64, _: &[String]) -> Result<String> {
            self.switches
                .lock()
                .unwrap()
                .push(format!("{count} {freq}"));
            *self.channel.lock().unwrap() = (freq - 2407) / 5;
            Ok("OK".into())
        }
        fn pause(&self, _: u64) {}
    }
    impl FakeIw {
        fn set_busy(&self, b: &[(i64, u64)]) {
            *self.busy.lock().unwrap() = b.iter().copied().collect();
        }
    }

