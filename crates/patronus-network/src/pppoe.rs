//! PPPoE client links (USE=pppoe, cargo feature `pppoe`).
//!
//! Each `pppoe_links` row becomes one pppd instance (kernel PPPoE plugin)
//! that creates the ppp device named by the row (`ifname`), supervised as
//! `patronus-pppoe@<name>` (systemd) / `patronus-pppoe.<name>` (OpenRC) /
//! directly in containers. The peer options -- including the password,
//! hence mode 0600 -- are generated into
//! `<net state dir>/ppp/<name>.options` and passed with `pppd file`, so
//! nothing in /etc/ppp is edited and several links can coexist.
//!
//! (This replaces an older module that was never compiled: it wrote
//! /etc/ppp/options but started `pppd call provider`, which reads
//! /etc/ppp/peers/provider, and killed every pppd on disconnect.)

use crate::netconf::PppoeConfig;
use crate::supervise::{which, DaemonSpec, NetPaths};
use patronus_core::{Error, Result};

pub const SERVICE: &str = crate::PPPOE_SERVICE;

/// pppd's PPPoE plugin: `pppoe.so` (ppp >= 2.4.9 / 2.5) or the older
/// `rp-pppoe.so`.
pub fn plugin_name() -> &'static str {
    fn has(dir: &std::path::Path, depth: u32) -> bool {
        if dir.join("pppoe.so").exists() {
            return true;
        }
        if depth == 0 {
            return false;
        }
        std::fs::read_dir(dir)
            .map(|rd| {
                rd.flatten()
                    .filter(|e| e.path().is_dir())
                    .any(|e| has(&e.path(), depth - 1))
            })
            .unwrap_or(false)
    }
    // /usr/lib/pppd/<version>/pppoe.so, /usr/lib/<triplet>/pppd/<version>/...
    for root in ["/usr/lib/pppd", "/usr/lib64/pppd"] {
        if has(std::path::Path::new(root), 1) {
            return "pppoe.so";
        }
    }
    for root in ["/usr/lib", "/usr/lib64"] {
        if let Ok(rd) = std::fs::read_dir(root) {
            for e in rd.flatten() {
                if has(&e.path().join("pppd"), 1) {
                    return "pppoe.so";
                }
            }
        }
    }
    "rp-pppoe.so"
}

fn quote(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

/// pppd options for one link.
pub fn render_options(p: &PppoeConfig, plugin: &str) -> String {
    let mut o = format!(
        "# Generated by Patronus for PPPoE link {name}; do not edit\n\
         # (Interfaces page -> PPPoE).\n\
         plugin {plugin}\n\
         nic-{parent}\n\
         ifname {name}\n\
         linkname {name}\n\
         user {user}\n\
         password {pass}\n\
         hide-password\n\
         noauth\n\
         noipdefault\n\
         persist\n\
         maxfail 0\n\
         holdoff 5\n\
         lcp-echo-interval 10\n\
         lcp-echo-failure 6\n\
         mtu {mtu}\n\
         mru {mtu}\n",
        name = p.name,
        parent = p.parent,
        user = quote(&p.username),
        pass = quote(&p.password),
        mtu = p.mtu,
    );
    if let Some(s) = p.service_name.as_deref().filter(|s| !s.is_empty()) {
        o.push_str(&format!("rp_pppoe_service {}\n", quote(s)));
    }
    if p.default_route {
        o.push_str("defaultroute\n");
    }
    if p.use_peer_dns {
        o.push_str("usepeerdns\n");
    }
    if p.ipv6 {
        o.push_str("+ipv6\n");
    }
    o
}

/// The daemon spec for one link.
pub fn spec(p: &PppoeConfig, paths: &NetPaths) -> Result<DaemonSpec> {
    let pppd = which("pppd").ok_or_else(|| {
        Error::Network("pppd is not installed (net-dialup/ppp, USE=pppoe)".into())
    })?;
    let opts = paths
        .state_dir
        .join("ppp")
        .join(format!("{}.options", p.name));
    Ok(DaemonSpec {
        service: SERVICE,
        instance: p.name.clone(),
        argv: vec![
            pppd.to_string_lossy().into(),
            "file".into(),
            opts.to_string_lossy().into(),
            "nodetach".into(),
        ],
        files: vec![(opts, render_options(p, plugin_name()), 0o600)],
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn options_quote_credentials_and_name_the_device() {
        let p = PppoeConfig {
            name: "pppoe0".into(),
            parent: "eth0".into(),
            username: "u@isp".into(),
            password: "pa\"ss\\word".into(),
            service_name: Some("fiber".into()),
            mtu: 1492,
            default_route: true,
            use_peer_dns: false,
            ipv6: true,
            enabled: true,
            description: None,
        };
        let o = render_options(&p, "pppoe.so");
        assert!(o.contains("plugin pppoe.so\nnic-eth0\nifname pppoe0\n"));
        assert!(o.contains("password \"pa\\\"ss\\\\word\"\n"));
        assert!(o.contains("defaultroute\n") && !o.contains("usepeerdns"));
        assert!(o.contains("+ipv6") && o.contains("rp_pppoe_service \"fiber\""));
    }
}
