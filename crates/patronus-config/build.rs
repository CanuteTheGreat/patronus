//! Collects `migrations/NNNN_<lane>_<description>.sql` into a generated
//! table, so a lane adds a migration by adding ONE file -- no shared list to
//! edit (and fight over) in Rust source. See AGENTS.md "Config store".

use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("migrations");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut entries: Vec<(u32, String, String)> = Vec::new();
    for entry in std::fs::read_dir(&dir).expect("read migrations/") {
        let path = entry.expect("dir entry").path();
        println!("cargo:rerun-if-changed={}", path.display());
        if path.extension().and_then(|e| e.to_str()) != Some("sql") {
            continue;
        }
        let file = path.file_name().unwrap().to_string_lossy().to_string();
        let (num, rest) = file
            .split_once('_')
            .unwrap_or_else(|| panic!("migration {file}: expected NNNN_<lane>_<desc>.sql"));
        let version: u32 = num
            .parse()
            .unwrap_or_else(|_| panic!("migration {file}: {num:?} is not a number"));
        let name = rest.trim_end_matches(".sql").to_string();
        entries.push((version, name, path.display().to_string()));
    }
    entries.sort();
    for pair in entries.windows(2) {
        if pair[0].0 == pair[1].0 {
            panic!(
                "duplicate migration version {} ({} and {}); each lane has its own number range, see AGENTS.md",
                pair[0].0, pair[0].1, pair[1].1
            );
        }
    }

    let mut out =
        String::from("/// Generated by build.rs from migrations/*.sql, in version order.\n");
    out.push_str("pub static MIGRATIONS: &[Migration] = &[\n");
    for (version, name, path) in &entries {
        writeln!(
            out,
            "    Migration {{ version: {version}, name: {name:?}, sql: include_str!({path:?}) }},"
        )
        .unwrap();
    }
    out.push_str("];\n");
    let dest = Path::new(&std::env::var("OUT_DIR").unwrap()).join("migrations.rs");
    std::fs::write(dest, out).expect("write migrations.rs");
}
