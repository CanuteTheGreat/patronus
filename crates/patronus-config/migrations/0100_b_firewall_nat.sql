-- Lane B (firewall & NAT): rule logging, schedules, address family,
-- explicit rule order, port-forward inbound interface, NAT reflection,
-- 1:1 NAT, aliases (nftables sets) and schedules.

-- Filter rules ---------------------------------------------------------
-- log: 1 = `log prefix "patronus[<id>] "` before the verdict.
ALTER TABLE firewall_rules ADD COLUMN log INTEGER NOT NULL DEFAULT 0;
-- schedule: name of a firewall_schedules row; the rule is enforced only
-- while that schedule is active. NULL = always.
ALTER TABLE firewall_rules ADD COLUMN schedule TEXT;
-- ip_version: 'ipv4' / 'ipv6' restricts the rule to one family; NULL =
-- implied by the addresses, or both.
ALTER TABLE firewall_rules ADD COLUMN ip_version TEXT;

-- Explicit order: `priority` is now the rule's position. System rules
-- (anti-lockout) stay pinned at -1000; every other rule is renumbered
-- 10, 20, 30, ... in its current evaluation order so rules can be moved.
UPDATE firewall_rules
SET priority = (
    SELECT rn * 10 FROM (
        SELECT id, ROW_NUMBER() OVER (ORDER BY priority ASC, id ASC) AS rn
        FROM firewall_rules WHERE origin != 'system'
    ) AS ordered WHERE ordered.id = firewall_rules.id
)
WHERE origin != 'system';

-- NAT rules ------------------------------------------------------------
-- interface_in: the interface a port forward (DNAT) / 1:1 NAT matches
-- inbound traffic on. Lane A stored a DNAT's interface in interface_out,
-- which rendered `oifname` in prerouting (never matches); move it.
ALTER TABLE nat_rules ADD COLUMN interface_in TEXT;
UPDATE nat_rules SET interface_in = interface_out, interface_out = NULL
WHERE nat_type = 'dnat';
-- reflection: 1 = NAT reflection (hairpin) for this port forward.
ALTER TABLE nat_rules ADD COLUMN reflection INTEGER NOT NULL DEFAULT 0;
-- external_address: the WAN-side address of a 1:1 NAT (nat_type
-- 'onetoone'); to_address is the internal address.
ALTER TABLE nat_rules ADD COLUMN external_address TEXT;

-- Automatic outbound NAT (one masquerade per WAN interface, generated by
-- the firewall applier from the interface roles, see
-- system_config 'firewall.outbound_nat_mode') replaces the seeded
-- "Outbound NAT" row, which only ever covered '@wan'.
DELETE FROM nat_rules
WHERE origin = 'default' AND nat_type = 'masquerade' AND interface_out = '@wan'
  AND source IS NULL AND destination IS NULL;

-- Aliases --------------------------------------------------------------
-- Rendered as nftables sets (`alias_<name>_v4` / `_v6` for host aliases,
-- `alias_<name>_ports` for port aliases). Rules reference them as `$name`.
-- Editing an alias only replaces the set's elements (no ruleset reload).
CREATE TABLE IF NOT EXISTS firewall_aliases (
    name TEXT PRIMARY KEY,
    alias_type TEXT NOT NULL,          -- 'host' or 'port'
    entries TEXT NOT NULL,             -- JSON array of strings
    description TEXT,
    updated_at INTEGER NOT NULL
);

-- Schedules ------------------------------------------------------------
-- A rule with a schedule is enforced only on `days` between start_time
-- and end_time (local time, HH:MM; end < start wraps past midnight).
CREATE TABLE IF NOT EXISTS firewall_schedules (
    name TEXT PRIMARY KEY,
    days TEXT NOT NULL,                -- comma list: mon,tue,wed,thu,fri,sat,sun
    start_time TEXT NOT NULL,          -- HH:MM
    end_time TEXT NOT NULL,            -- HH:MM
    description TEXT,
    updated_at INTEGER NOT NULL
);
