-- Lane F (VPN): WireGuard tunnels and IPsec IKEv2 site-to-site tunnels,
-- applied by patronus-network/src/wireguard.rs (boot phase "interfaces",
-- after the lane C interfaces) and patronus-network/src/ipsec.rs (phase
-- "services": strongSwan via swanctl). Private keys and pre-shared keys live
-- here (the store is 0600/0640 and owned by the service user) and are never
-- returned by the API; backups carry them, so backup files are 0600 and only
-- admins may download them.

-- One WireGuard interface (kernel device) = one tunnel endpoint.
CREATE TABLE IF NOT EXISTS wg_interfaces (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    -- kernel device name (wg0, wg1, ...)
    name TEXT NOT NULL UNIQUE,
    enabled INTEGER NOT NULL DEFAULT 1,
    -- base64 Curve25519 private key (generated by Patronus)
    private_key TEXT NOT NULL,
    listen_port INTEGER NOT NULL,
    -- comma-separated addresses with prefix on the tunnel (10.99.0.1/24, fd00:99::1/64)
    addresses TEXT NOT NULL DEFAULT '',
    mtu INTEGER,
    -- client config export: public host[:port] clients connect to, DNS
    -- servers they use and what they route into the tunnel
    endpoint TEXT,
    client_dns TEXT,
    client_allowed_ips TEXT NOT NULL DEFAULT '0.0.0.0/0, ::/0',
    description TEXT,
    updated_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS wg_peers (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    interface TEXT NOT NULL REFERENCES wg_interfaces(name) ON DELETE CASCADE ON UPDATE CASCADE,
    name TEXT NOT NULL,
    enabled INTEGER NOT NULL DEFAULT 1,
    public_key TEXT NOT NULL,
    -- only for peers whose key pair Patronus generated (road-warrior
    -- clients): needed to export the client config / QR code
    private_key TEXT,
    preshared_key TEXT,
    -- networks routed to this peer (a client's tunnel address /32, or a
    -- remote site's LAN), comma-separated
    allowed_ips TEXT NOT NULL,
    -- host:port of a site-to-site peer (NULL = the peer connects to us)
    endpoint TEXT,
    persistent_keepalive INTEGER,
    description TEXT,
    updated_at INTEGER NOT NULL,
    UNIQUE (interface, name),
    UNIQUE (interface, public_key)
);

-- IPsec IKEv2 site-to-site tunnel (strongSwan swanctl connection with one
-- CHILD_SA), pre-shared key authentication.
CREATE TABLE IF NOT EXISTS ipsec_tunnels (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL UNIQUE,
    enabled INTEGER NOT NULL DEFAULT 1,
    -- local IKE address (NULL = any local address)
    local_address TEXT,
    -- peer address or hostname; '%any' = only respond
    remote_address TEXT NOT NULL,
    -- IKE identities (NULL = the address)
    local_id TEXT,
    remote_id TEXT,
    psk TEXT NOT NULL,
    -- traffic selectors: comma-separated subnets on each side
    local_ts TEXT NOT NULL,
    remote_ts TEXT NOT NULL,
    ike_proposals TEXT NOT NULL DEFAULT 'aes256gcm16-prfsha384-ecp384,aes256-sha256-modp2048',
    esp_proposals TEXT NOT NULL DEFAULT 'aes256gcm16-ecp384,aes256-sha256-modp2048',
    -- start = initiate at load, trap = on first matching packet, none = respond only
    start_action TEXT NOT NULL DEFAULT 'start',
    dpd_delay INTEGER NOT NULL DEFAULT 30,
    description TEXT,
    updated_at INTEGER NOT NULL
);
