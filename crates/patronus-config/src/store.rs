    /// Insert a firewall rule with an explicit origin, returning its id.
    /// A caller-supplied `rule.id` is kept (seeding uses fixed ids).
    pub async fn insert_firewall_rule(
        &self,
        rule: &FirewallRule,
        origin: RuleOrigin,
    ) -> Result<i64> {
        let now = chrono::Utc::now().timestamp();
        let result = sqlx::query(
            "INSERT INTO firewall_rules
             (id, name, enabled, chain, action, source, destination, protocol, sport, dport,
              interface_in, interface_out, comment, priority, origin, created_at, updated_at)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        )
        .bind(rule.id.map(|i| i as i64))
        .bind(&rule.name)
        .bind(rule.enabled as i32)
        .bind(rule.chain.to_string())
        .bind(rule.action.to_string())
        .bind(&rule.source)
        .bind(&rule.destination)
        .bind(rule.protocol.as_ref().map(|p| p.to_string()))
        .bind(port_json(rule.sport.as_ref()))
        .bind(port_json(rule.dport.as_ref()))
        .bind(&rule.interface_in)
        .bind(&rule.interface_out)
        .bind(&rule.comment)
        .bind(priority_for(origin))
        .bind(origin.as_str())
        .bind(now)
        .bind(now)
        .execute(self.pool()?)
        .await
        .map_err(db_err("Failed to save firewall rule"))?;
        Ok(result.last_insert_rowid())
    }

    /// Replace the contents of firewall rule `id` (origin and priority are
    /// kept). Errors if the rule does not exist or is a system rule.
    pub async fn update_firewall_rule(&self, id: u64, rule: &FirewallRule) -> Result<()> {
        match self.get_firewall_rule(id).await? {
            None => return Err(Error::Config(format!("Rule {id} not found"))),
            Some((_, RuleOrigin::System)) => {
                return Err(Error::Config(format!(
                "Invalid request: rule {id} is a system rule (anti-lockout) and cannot be edited"
            )))
            }
            Some(_) => {}
        }
        sqlx::query(
            "UPDATE firewall_rules SET name = ?, enabled = ?, chain = ?, action = ?, source = ?,
                 destination = ?, protocol = ?, sport = ?, dport = ?, interface_in = ?,
                 interface_out = ?, comment = ?, updated_at = ?
             WHERE id = ?",
        )
        .bind(&rule.name)
        .bind(rule.enabled as i32)
        .bind(rule.chain.to_string())
        .bind(rule.action.to_string())
        .bind(&rule.source)
        .bind(&rule.destination)
        .bind(rule.protocol.as_ref().map(|p| p.to_string()))
        .bind(port_json(rule.sport.as_ref()))
        .bind(port_json(rule.dport.as_ref()))
        .bind(&rule.interface_in)
        .bind(&rule.interface_out)
        .bind(&rule.comment)
        .bind(chrono::Utc::now().timestamp())
        .bind(id as i64)
        .execute(self.pool()?)
        .await
        .map_err(db_err("Failed to update firewall rule"))?;
        Ok(())
    }

    /// One firewall rule and its origin.
    pub async fn get_firewall_rule(&self, id: u64) -> Result<Option<(FirewallRule, RuleOrigin)>> {
        Ok(self
            .load_firewall_rules_with_origin()
            .await?
            .into_iter()
            .find(|(r, _)| r.id == Some(id)))
    }

    /// Load all firewall rules, in evaluation order.
    pub async fn load_firewall_rules(&self) -> Result<Vec<FirewallRule>> {
        Ok(self
            .load_firewall_rules_with_origin()
            .await?
            .into_iter()
            .map(|(r, _)| r)
            .collect())
    }

    /// Load all firewall rules with their origin, in evaluation order
    /// (priority, then id: system rules first).
    pub async fn load_firewall_rules_with_origin(&self) -> Result<Vec<(FirewallRule, RuleOrigin)>> {
        let rows = sqlx::query(
            "SELECT id, name, enabled, chain, action, source, destination, protocol,
                    sport, dport, interface_in, interface_out, comment, origin
             FROM firewall_rules
             ORDER BY priority ASC, id ASC",
        )
        .fetch_all(self.pool()?)
        .await
        .map_err(db_err("Failed to load firewall rules"))?;

        let mut rules = Vec::new();
        for row in rows {
            let id: i64 = row.get("id");
            let chain = match row.get::<String, _>("chain").as_str() {
                "input" => ChainType::Input,
                "output" => ChainType::Output,
                "forward" => ChainType::Forward,
                other => {
                    return Err(Error::Config(format!(
                        "firewall rule {id}: unknown chain {other:?}"
                    )))
                }
            };
            let action = match row.get::<String, _>("action").as_str() {
                "accept" => FirewallAction::Accept,
                "drop" => FirewallAction::Drop,
                "reject" => FirewallAction::Reject,
                other => {
                    return Err(Error::Config(format!(
                        "firewall rule {id}: unknown action {other:?}"
                    )))
                }
            };
            rules.push((
                FirewallRule {
                    id: Some(id as u64),
                    name: row.get("name"),
                    enabled: row.get::<i32, _>("enabled") != 0,
                    chain,
                    action,
                    source: row.get("source"),
                    destination: row.get("destination"),
                    protocol: parse_protocol(id, row.get("protocol"))?,
                    sport: parse_port(id, "sport", row.get("sport"))?,
                    dport: parse_port(id, "dport", row.get("dport"))?,
                    interface_in: row.get("interface_in"),
                    interface_out: row.get("interface_out"),
                    comment: row.get("comment"),
                },
                RuleOrigin::parse(&row.get::<String, _>("origin")),
            ));
        }
        Ok(rules)
    }

    /// Delete a firewall rule. System rules (anti-lockout) are refused.
    pub async fn delete_firewall_rule(&self, id: u64) -> Result<()> {
        if let Some((_, RuleOrigin::System)) = self.get_firewall_rule(id).await? {
            return Err(Error::Config(format!(
                "Invalid request: rule {id} is a system rule (anti-lockout) and cannot be deleted"
            )));
        }
        sqlx::query("DELETE FROM firewall_rules WHERE id = ?")
            .bind(id as i64)
            .execute(self.pool()?)
            .await
            .map_err(db_err("Failed to delete firewall rule"))?;
        Ok(())
    }

