    /// Load all NAT rules, in evaluation order.
    pub async fn load_nat_rules(&self) -> Result<Vec<NatRule>> {
        Ok(self
            .load_nat_rules_with_origin()
            .await?
            .into_iter()
            .map(|(r, _)| r)
            .collect())
    }

    /// Load all NAT rules with their origin.
    pub async fn load_nat_rules_with_origin(&self) -> Result<Vec<(NatRule, RuleOrigin)>> {
        let rows = sqlx::query(
            "SELECT id, name, enabled, nat_type, to_address, to_port, source, destination,
                    protocol, dport, interface_out, comment, origin
             FROM nat_rules
             ORDER BY priority ASC, id ASC",
        )
        .fetch_all(self.pool()?)
        .await
        .map_err(db_err("Failed to load NAT rules"))?;

        let mut rules = Vec::new();
        for row in rows {
            let id: i64 = row.get("id");
            let to_address: Option<String> = row.get("to_address");
            let addr = || -> Result<std::net::IpAddr> {
                to_address.as_deref().unwrap_or("").parse().map_err(|_| {
                    Error::Config(format!("NAT rule {id}: bad to_address {to_address:?}"))
                })
            };
            let nat_type = match row.get::<String, _>("nat_type").as_str() {
                "masquerade" => NatType::Masquerade,
                "snat" => NatType::Snat {
                    to_address: addr()?,
                },
                "dnat" => NatType::Dnat {
                    to_address: addr()?,
                    to_port: row.get::<Option<i64>, _>("to_port").map(|p| p as u16),
                },
                other => {
                    return Err(Error::Config(format!(
                        "NAT rule {id}: unknown nat_type {other:?}"
                    )))
                }
            };
            rules.push((
                NatRule {
                    id: Some(id as u64),
                    name: row.get("name"),
                    enabled: row.get::<i32, _>("enabled") != 0,
                    nat_type,
                    source: row.get("source"),
                    destination: row.get("destination"),
                    protocol: parse_protocol(id, row.get("protocol"))?,
                    dport: parse_port(id, "dport", row.get("dport"))?,
                    interface_out: row.get("interface_out"),
                    comment: row.get("comment"),
                },
                RuleOrigin::parse(&row.get::<String, _>("origin")),
            ));
        }
        Ok(rules)
    }

    /// Delete a NAT rule. System rules are refused.
    pub async fn delete_nat_rule(&self, id: u64) -> Result<()> {
        let origin = self
            .load_nat_rules_with_origin()
            .await?
            .into_iter()
            .find(|(r, _)| r.id == Some(id))
            .map(|(_, o)| o);
        if origin == Some(RuleOrigin::System) {
            return Err(Error::Config(format!(
                "Invalid request: NAT rule {id} is a system rule and cannot be deleted"
            )));
        }
        sqlx::query("DELETE FROM nat_rules WHERE id = ?")
            .bind(id as i64)
            .execute(self.pool()?)
            .await
            .map_err(db_err("Failed to delete NAT rule"))?;
        Ok(())
    }

    /// Delete every firewall and NAT row with this origin and name (the
    /// GitOps engine's "replace resource" primitive).
    pub async fn delete_rules_by_name(&self, origin: RuleOrigin, name: &str) -> Result<()> {
        for table in ["firewall_rules", "nat_rules"] {
            sqlx::query(&format!(
                "DELETE FROM {table} WHERE origin = ? AND name = ?"
            ))
            .bind(origin.as_str())
            .bind(name)
            .execute(self.pool()?)
            .await
            .map_err(db_err("Failed to delete rules by name"))?;
        }
        Ok(())
    }

