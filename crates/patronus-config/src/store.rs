    #[tokio::test]
    async fn file_store_is_created_migrated_and_persists_across_reopen() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("sub/config.db");
        {
            let s = ConfigStore::open(&path).await.unwrap();
            let id = s.save_firewall_rule(&rule("persist-me")).await.unwrap();
            assert!(id > 0);
            s.set_sysctl("net.ipv4.ip_forward", "1", RuleOrigin::Default)
                .await
                .unwrap();
            s.set_interface_role("eth1", Some("lan")).await.unwrap();
            s.close().await;
        }
        let s = ConfigStore::open(&path).await.unwrap();
        let rules = s.load_firewall_rules_with_origin().await.unwrap();
        assert_eq!(rules.len(), 1);
        assert_eq!(rules[0].0.name, "persist-me");
        assert_eq!(rules[0].0.chain, ChainType::Forward);
        assert_eq!(rules[0].0.dport, Some(PortSpec::Multiple(vec![22, 8443])));
        assert_eq!(rules[0].1, RuleOrigin::User);
        assert_eq!(
            s.load_sysctls().await.unwrap(),
            vec![("net.ipv4.ip_forward".into(), "1".into())]
        );
        assert_eq!(
            s.interfaces_with_role("lan").await.unwrap(),
            vec!["eth1".to_string()]
        );
        // Re-opening must not re-run migrations.
        let n: i64 = sqlx::query("SELECT count(*) FROM schema_migrations")
            .fetch_one(s.pool().unwrap())
            .await
            .unwrap()
            .get(0);
        assert_eq!(n as usize, crate::migrate::MIGRATIONS.len());
    }

