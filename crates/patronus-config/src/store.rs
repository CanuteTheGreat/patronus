//! Persistent configuration store (SQLite).
//!
//! This is the single source of truth for every subsystem: the web UI, the
//! CLI and the GitOps engine write rows here, and the per-subsystem
//! [`Applier`](crate::applier::Applier)s read them back to program the
//! kernel/daemons -- at every change and again at boot (`patronus apply`).
//!
//! Conventions (also in AGENTS.md):
//! - Each lane owns its tables and adds them with a migration file in
//!   `crates/patronus-config/migrations/` inside its number range
//!   (see [`crate::migrate::LANE_RANGES`]).
//! - Typed accessors for a lane's tables live in that lane's own module
//!   (next to its applier) and use [`ConfigStore::pool`]; this file only
//!   holds the shared/foundation ones.

