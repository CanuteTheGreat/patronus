    /// Assign (or with `None`, clear) the logical role of an interface.
    pub async fn set_interface_role(&self, name: &str, role: Option<&str>) -> Result<()> {
        if let Some(r) = role {
            if !is_valid_role(r) {
                return Err(Error::Config(format!(
                    "Invalid interface role {r:?} (wan, lan or opt<N>)"
                )));
            }
        }
        sqlx::query(
            "INSERT INTO interfaces (name, role, updated_at) VALUES (?, ?, ?)
             ON CONFLICT(name) DO UPDATE SET role = excluded.role, updated_at = excluded.updated_at",
        )
        .bind(name)
        .bind(role)
        .bind(chrono::Utc::now().timestamp())
        .execute(self.pool()?)
        .await
        .map_err(db_err("Failed to set interface role"))?;
        Ok(())
    }

    /// (interface, role) for every enabled interface with a role, by name.
    pub async fn interface_roles(&self) -> Result<Vec<(String, String)>> {
        let rows = sqlx::query(
            "SELECT name, role FROM interfaces WHERE role IS NOT NULL AND enabled = 1 ORDER BY name",
        )
        .fetch_all(self.pool()?)
        .await
        .map_err(db_err("Failed to load interface roles"))?;
        Ok(rows.iter().map(|r| (r.get(0), r.get(1))).collect())
    }

    /// Interfaces that carry `role` (e.g. "lan").
    pub async fn interfaces_with_role(&self, role: &str) -> Result<Vec<String>> {
        Ok(self
            .interface_roles()
            .await?
            .into_iter()
            .filter(|(_, r)| r == role)
            .map(|(n, _)| n)
            .collect())
    }

