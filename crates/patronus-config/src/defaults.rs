//! First-boot defaults: interface roles from `/etc/patronus/patronus.toml`
//! and the safe default ruleset.
//!
//! A fresh Patronus box must route LAN -> WAN and stay manageable without
//! anyone touching the UI first, so on the first `patronus apply` (or the
//! first `patronus-web` start when no boot unit ran, e.g. in a container)
//! the store is seeded with:
//!
//! | rule | origin | what |
//! |---|---|---|
//! | Anti-lockout | system | input, `@mgmt`, tcp 22 + the web UI ports (443, 80) accept |
//! | Allow LAN to firewall | default | input, `@lan` accept |
//! | Allow LAN to any | default | forward, `@lan` accept |
//! | Outbound NAT | automatic | IPv4 masquerade on every WAN interface (generated by the firewall applier, `firewall.outbound_nat_mode`) |
//! | ip_forward v4/v6 | default | `net.ipv4.ip_forward=1`, `net.ipv6.conf.all.forwarding=1` |
//!
//! Everything else -- in particular anything arriving on the WAN -- hits
//! the base ruleset's `policy drop`. Defaults are seeded once (deleting
//! one is respected on the next boot); the anti-lockout rule is a system
//! rule that the API refuses to delete.
//!
//! `@mgmt` is resolved by the firewall applier to the LAN interfaces, or to
//! the WAN if there is no LAN (single-NIC box, like pfSense), or to every
//! interface if no role is assigned at all -- so the box can always be
//! reached to finish setting it up.

use crate::store::{ConfigStore, RuleOrigin};
use patronus_core::types::{ChainType, FirewallAction, FirewallRule, NatRule, PortSpec, Protocol};
use patronus_core::{Error, Result};
use std::path::{Path, PathBuf};

/// Installed bootstrap file (written by the installer / catalyst ISO).
pub const DEFAULT_BOOTSTRAP_PATH: &str = "/etc/patronus/patronus.toml";

/// `system_config` key recording that the defaults were seeded.
pub const DEFAULTS_SEEDED_KEY: &str = "defaults_seeded_at";

/// Ports the anti-lockout rule keeps open: SSH and the web UI's standard ports
/// (the web listeners themselves come from `webui::WebSettings`, which the
/// firewall applier renders into the rule on every apply).
pub const ANTI_LOCKOUT_PORTS: &[u16] = &[22, 443, 80];

/// Ports the anti-lockout rule opens at first-boot seeding: [`ANTI_LOCKOUT_PORTS`],
/// or `$PATRONUS_ANTI_LOCKOUT_PORTS` (comma list) when set. The router image sets
/// it to `22,80,443` because its web UI listens on 443 (+ the 80 redirect).
pub fn anti_lockout_ports() -> Vec<u16> {
    parse_anti_lockout_ports(std::env::var("PATRONUS_ANTI_LOCKOUT_PORTS").ok().as_deref())
}

/// The comma list of `$PATRONUS_ANTI_LOCKOUT_PORTS` (`None` = unset): entries
/// that are not a port are dropped, and an empty result falls back to
/// [`ANTI_LOCKOUT_PORTS`].
fn parse_anti_lockout_ports(list: Option<&str>) -> Vec<u16> {
    list.map(|v| {
        v.split(',')
            .filter_map(|p| p.trim().parse::<u16>().ok())
            .collect::<Vec<_>>()
    })
    .filter(|v| !v.is_empty())
    .unwrap_or_else(|| ANTI_LOCKOUT_PORTS.to_vec())
}

/// `system_config` key: while an interface carries the `mgmt` role (a
/// dedicated management network), SSH and the web UI answer ONLY there
/// (`1`, the default) or also on the other interfaces (`0`).
pub const MGMT_ONLY_KEY: &str = "firewall.mgmt_only";

/// [`MGMT_ONLY_KEY`]: on unless it is set to `0` / `false` / `off` / `no`.
pub async fn mgmt_only(store: &ConfigStore) -> bool {
    parse_mgmt_only(
        store
            .load_system_config(MGMT_ONLY_KEY)
            .await
            .ok()
            .flatten()
            .as_deref(),
    )
}

/// The value of [`MGMT_ONLY_KEY`] (`None` = unset = on).
pub fn parse_mgmt_only(v: Option<&str>) -> bool {
    !matches!(
        v.map(|s| s.trim().to_ascii_lowercase()).as_deref(),
        Some("0" | "false" | "off" | "no")
    )
}

/// `system_config` key of the managed SSH server's port (lane H/L3).
pub const SSH_PORT_KEY: &str = "ssh.port";

/// The SSH port the anti-lockout rule must keep open (`ssh.port`, default 22).
pub async fn ssh_port(store: &ConfigStore) -> u16 {
    store
        .load_system_config(SSH_PORT_KEY)
        .await
        .ok()
        .flatten()
        .and_then(|v| v.trim().parse::<u16>().ok())
        .filter(|p| *p != 0)
        .unwrap_or(22)
}

/// The stored anti-lockout rule opens tcp/22 (seeded before `ssh.port`
/// existed): make a system "Anti-lockout" rule open `ssh_port` instead.
pub fn follow_ssh_port(rule: &mut FirewallRule, origin: RuleOrigin, ssh_port: u16) {
    if origin != RuleOrigin::System || rule.name != "Anti-lockout" || ssh_port == 22 {
        return;
    }
    if let Some(PortSpec::Multiple(ports)) = &mut rule.dport {
        if ports.contains(&22) {
            ports.retain(|p| *p != 22 && *p != ssh_port);
            ports.insert(0, ssh_port);
        }
    }
}

/// The bootstrap file path: `$PATRONUS_BOOTSTRAP` or the default.
pub fn default_bootstrap_path() -> PathBuf {
    std::env::var_os("PATRONUS_BOOTSTRAP")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(DEFAULT_BOOTSTRAP_PATH))
}

/// Interface roles (and the virtual devices they sit on) read from the
/// `[network]` section of patronus.toml.
///
/// ```toml
/// [network]
/// wan_interface  = "bond0.100"   # also wan_interfaces = [...]
/// lan_interface  = "bond0.30"
/// mgmt_interface = "bond0.20"    # optional dedicated management network
///
/// [[network.bond]]               # link aggregation created at first boot
/// name = "bond0"
/// members = ["enp1s0", "enp2s0"]
/// mode = "802.3ad"               # 802.3ad | active-backup | balance-xor | ...
/// xmit_hash_policy = "layer2+3"  # optional
/// lacp_rate = "fast"             # optional, 802.3ad only
/// miimon = 100                   # optional (ms)
///
/// [[network.vlan]]               # 802.1Q VLAN created at first boot
/// parent = "bond0"
/// tag = 100
/// name = "bond0.100"             # optional, default <parent>.<tag>
/// ```
///
/// Bonds and VLANs declared here are created by the interfaces applier on
/// the first boot (`patronus apply`), so a role may name them before they
/// exist in the kernel. docs/ISO-INSTALL.md lists every key.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Bootstrap {
    pub wan: Vec<String>,
    pub lan: Vec<String>,
    /// Dedicated management network (role `mgmt`): carries the anti-lockout
    /// rule (SSH + web UI) instead of the LAN.
    pub mgmt: Vec<String>,
    /// `opt_interfaces = [...]`: OPT1, OPT2 ... in that order (roles opt1, opt2 ...)
    pub opt: Vec<String>,
    pub bonds: Vec<BootBond>,
    pub vlans: Vec<BootVlan>,
}

/// A `[[network.bond]]` entry of patronus.toml.
#[derive(Debug, Clone, Default, PartialEq, serde::Deserialize, serde::Serialize)]
pub struct BootBond {
    pub name: String,
    #[serde(default)]
    pub members: Vec<String>,
    #[serde(default = "default_bond_mode")]
    pub mode: String,
    #[serde(default)]
    pub xmit_hash_policy: Option<String>,
    #[serde(default)]
    pub lacp_rate: Option<String>,
    #[serde(default)]
    pub miimon: Option<u32>,
    #[serde(default)]
    pub primary: Option<String>,
}

/// Mode of a `[[network.bond]]` entry without `mode`.
pub const DEFAULT_BOND_MODE: &str = "active-backup";

fn default_bond_mode() -> String {
    DEFAULT_BOND_MODE.into()
}

/// Bond modes of Linux bonding (`l2_bonds.mode`).
pub const BOND_MODES: &[&str] = &[
    "active-backup",
    "802.3ad",
    "balance-xor",
    "balance-rr",
    "broadcast",
    "balance-tlb",
    "balance-alb",
];

/// Transmit hash policies (`xmit_hash_policy`).
pub const BOND_HASH_POLICIES: &[&str] = &[
    "layer2",
    "layer2+3",
    "layer3+4",
    "encap2+3",
    "encap3+4",
    "vlan+srcmac",
];

/// A `[[network.vlan]]` entry of patronus.toml.
#[derive(Debug, Clone, Default, PartialEq, serde::Deserialize, serde::Serialize)]
pub struct BootVlan {
    pub parent: String,
    pub tag: u16,
    #[serde(default)]
    pub name: Option<String>,
}

impl BootVlan {
    /// The device name: `name`, or `<parent>.<tag>`.
    pub fn device(&self) -> String {
        self.name
            .clone()
            .filter(|n| !n.trim().is_empty())
            .unwrap_or_else(|| format!("{}.{}", self.parent, self.tag))
    }
}

#[derive(serde::Deserialize, Default)]
struct BootstrapFile {
    #[serde(default)]
    network: NetworkSection,
}

#[derive(serde::Deserialize, Default)]
struct NetworkSection {
    wan_interface: Option<String>,
    lan_interface: Option<String>,
    mgmt_interface: Option<String>,
    #[serde(default)]
    wan_interfaces: Vec<String>,
    #[serde(default)]
    lan_interfaces: Vec<String>,
    #[serde(default)]
    mgmt_interfaces: Vec<String>,
    #[serde(default)]
    bond: Vec<BootBond>,
    #[serde(default)]
    vlan: Vec<BootVlan>,
    #[serde(default)]
    opt_interfaces: Vec<String>,
}

/// Linux interface name rules (at most 15 bytes, no `/`, `:` or blanks).
fn ifname_ok(n: &str) -> bool {
    !n.is_empty()
        && n.len() <= 15
        && n != "."
        && n != ".."
        && n.bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'-' | b'_' | b'@'))
}

fn role_list(one: Option<String>, mut many: Vec<String>) -> Vec<String> {
    if let Some(x) = one {
        many.insert(0, x);
    }
    let mut out: Vec<String> = Vec::new();
    for x in many {
        if !x.trim().is_empty() && !out.contains(&x) {
            out.push(x);
        }
    }
    out
}

impl Bootstrap {
    /// Parse patronus.toml text. Bonds / VLANs that fail [`Self::validate`]
    /// are still returned: role assignment must not depend on them, and the
    /// first-boot network seeding refuses them with the plain-words reason.
    pub fn parse(text: &str) -> Result<Self> {
        let f: BootstrapFile =
            toml::from_str(text).map_err(|e| Error::Config(format!("patronus.toml: {e}")))?;
        let n = f.network;
        Ok(Bootstrap {
            wan: role_list(n.wan_interface, n.wan_interfaces),
            lan: role_list(n.lan_interface, n.lan_interfaces),
            mgmt: role_list(n.mgmt_interface, n.mgmt_interfaces),
            opt: role_list(None, n.opt_interfaces),
            bonds: n.bond,
            vlans: n.vlan,
        })
    }

    /// The first problem with the bonds / VLANs / roles, in plain words.
    pub fn validate(&self) -> Result<()> {
        let bad = |m: String| Err(Error::Config(format!("patronus.toml [network]: {m}")));
        let mut members: Vec<&str> = Vec::new();
        let mut names: Vec<String> = Vec::new();
        for b in &self.bonds {
            if !ifname_ok(&b.name) {
                return bad(format!(
                    "bond name {:?} is not a valid interface name",
                    b.name
                ));
            }
            if !BOND_MODES.contains(&b.mode.as_str()) {
                return bad(format!(
                    "bond {}: mode {:?} (one of {})",
                    b.name,
                    b.mode,
                    BOND_MODES.join(", ")
                ));
            }
            if b.members.is_empty() {
                return bad(format!("bond {} has no member ports", b.name));
            }
            for m in &b.members {
                if !ifname_ok(m) || m == &b.name {
                    return bad(format!("bond {}: member {m:?} is not a valid port", b.name));
                }
                if members.contains(&m.as_str()) {
                    return bad(format!("port {m} is a member of two bonds"));
                }
                members.push(m);
            }
            if let Some(h) = &b.xmit_hash_policy {
                if !BOND_HASH_POLICIES.contains(&h.as_str()) {
                    return bad(format!(
                        "bond {}: xmit_hash_policy {h:?} (one of {})",
                        b.name,
                        BOND_HASH_POLICIES.join(", ")
                    ));
                }
            }
            if let Some(r) = &b.lacp_rate {
                if r != "slow" && r != "fast" {
                    return bad(format!("bond {}: lacp_rate {r:?} (slow or fast)", b.name));
                }
                if b.mode != "802.3ad" {
                    return bad(format!("bond {}: lacp_rate needs mode 802.3ad", b.name));
                }
            }
            if let Some(ms) = b.miimon {
                if ms == 0 || ms > 10_000 {
                    return bad(format!("bond {}: miimon {ms} (1-10000 ms)", b.name));
                }
            }
            if let Some(p) = &b.primary {
                if !b.members.contains(p) {
                    return bad(format!("bond {}: primary {p} is not a member", b.name));
                }
            }
            if names.contains(&b.name) {
                return bad(format!("two devices are named {}", b.name));
            }
            names.push(b.name.clone());
        }
        for v in &self.vlans {
            if !(1..=4094).contains(&v.tag) {
                return bad(format!("VLAN tag {} on {} (1-4094)", v.tag, v.parent));
            }
            if !ifname_ok(&v.parent) {
                return bad(format!(
                    "VLAN {}: parent {:?} is not a valid interface",
                    v.tag, v.parent
                ));
            }
            let d = v.device();
            if !ifname_ok(&d) {
                return bad(format!(
                    "VLAN device name {d:?} is invalid or longer than 15 characters: set `name`"
                ));
            }
            if members.contains(&v.parent.as_str()) {
                return bad(format!(
                    "VLAN {d}: {} is a bond member; put the VLAN on the bond instead",
                    v.parent
                ));
            }
            if names.contains(&d) {
                return bad(format!("two devices are named {d}"));
            }
            names.push(d);
        }
        for (role, list) in [
            ("wan", &self.wan),
            ("lan", &self.lan),
            ("mgmt", &self.mgmt),
            ("opt", &self.opt),
        ] {
            for n in list {
                if members.contains(&n.as_str()) {
                    return bad(format!(
                        "{role} interface {n} is a bond member: give the role to the bond (or a VLAN on it)"
                    ));
                }
            }
        }
        for m in &self.mgmt {
            if self.wan.contains(m) || self.lan.contains(m) || self.opt.contains(m) {
                return bad(format!(
                    "the management network {m} is also the WAN, LAN or an OPT interface: use a separate port or VLAN, or leave mgmt_interface out"
                ));
            }
        }
        Ok(())
    }

    /// Bond and VLAN devices declared here (created at first boot); empty
    /// when the declaration is invalid.
    pub fn virtual_names(&self) -> Vec<String> {
        if self.validate().is_err() {
            return Vec::new();
        }
        let mut v: Vec<String> = self.bonds.iter().map(|b| b.name.clone()).collect();
        v.extend(self.vlans.iter().map(|x| x.device()));
        v
    }

    /// (interface, role) pairs in file order: wan, lan, mgmt, then opt1, opt2 ...
    pub fn roles(&self) -> Vec<(String, String)> {
        let mut v: Vec<(String, String)> = Vec::new();
        for n in &self.wan {
            v.push((n.clone(), "wan".into()));
        }
        for n in &self.lan {
            v.push((n.clone(), "lan".into()));
        }
        for n in &self.mgmt {
            v.push((n.clone(), "mgmt".into()));
        }
        for (i, n) in self.opt.iter().enumerate() {
            v.push((n.clone(), format!("opt{}", i + 1)));
        }
        v
    }

    /// Load the bootstrap file; `Ok(None)` if it does not exist.
    pub fn load(path: &Path) -> Result<Option<Self>> {
        match std::fs::read_to_string(path) {
            Ok(t) => Self::parse(&t).map(Some),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(Error::Config(format!("read {}: {e}", path.display()))),
        }
    }
}

/// Network interfaces present in the current network namespace
/// (`/sys/class/net`, which `ip netns exec` remounts per namespace).
pub fn existing_interfaces() -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir("/sys/class/net")
        .map(|d| {
            d.filter_map(|e| e.ok())
                .map(|e| e.file_name().to_string_lossy().to_string())
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

/// What [`ensure_defaults`] changed.
#[derive(Debug, Default, Clone, serde::Serialize)]
pub struct SeedReport {
    pub roles_assigned: Vec<(String, String)>,
    pub defaults_seeded: bool,
    pub warnings: Vec<String>,
}

/// Assign interface roles from the bootstrap file (only while the store has
/// no roles at all -- once roles exist the store wins) and seed the default
/// ruleset once. Safe to call at every boot.
pub async fn ensure_defaults(
    store: &ConfigStore,
    bootstrap: Option<&Bootstrap>,
    existing: &[String],
) -> Result<SeedReport> {
    let mut rep = SeedReport::default();

    if store.interface_roles().await?.is_empty() {
        if let Some(b) = bootstrap {
            let mut planned: Vec<(String, String)> = Vec::new();
            // bonds / VLANs the bootstrap declares are created by the interfaces applier
            // later in this same boot: a role may name them before they exist
            let declared = b.virtual_names();
            for (n, role) in b.roles() {
                if existing.contains(&n) || declared.contains(&n) {
                    planned.push((n, role));
                } else {
                    let w = format!(
                        "patronus.toml names {role} interface {n:?}, which does not exist \
                         (present: {}); not assigned",
                        existing.join(", ")
                    );
                    tracing::warn!("{w}");
                    rep.warnings.push(w);
                }
            }
            // one transaction: no reader ever sees a half-assigned set (WAN without LAN)
            if !planned.is_empty() {
                store.set_interface_roles(&planned).await?;
                rep.roles_assigned.extend(planned);
            }
        }
        if store.interface_roles().await?.is_empty() {
            let w = "no interface has a WAN/LAN role: management access (anti-lockout) is \
                     open on every interface and nothing is forwarded until roles are \
                     assigned ([network] in patronus.toml, or the Interfaces page)"
                .to_string();
            tracing::warn!("{w}");
            rep.warnings.push(w);
        }
    }

    if store
        .load_system_config(DEFAULTS_SEEDED_KEY)
        .await?
        .is_none()
    {
        // A store that carries rules somebody wrote is an upgrade, even when it is so old that
        // it has no "seeded" marker (the v0.1.0 layout): it must not get new behaviour.
        let upgraded = has_user_rules(store).await?;
        seed_default_rules(store).await?;
        // DNS rebinding protection is on for a new install; a store that
        // predates the setting keeps it off (split-horizon names would break)
        if !upgraded {
            sqlx::query(
                "INSERT OR IGNORE INTO lan_settings (key, value, updated_at) VALUES ('dns.rebind_protection', '1', ?)",
            )
            .bind(chrono::Utc::now().timestamp())
            .execute(store.pool()?)
            .await
            .map_err(|e| {
                patronus_core::Error::Config(format!("seed DNS rebind protection: {e}"))
            })?;
        }
        store
            .save_system_config(DEFAULTS_SEEDED_KEY, &chrono::Utc::now().to_rfc3339())
            .await?;
        store
            .audit(
                "system",
                "seed_defaults",
                "config",
                None,
                &serde_json::json!({"roles": rep.roles_assigned}),
            )
            .await?;
        rep.defaults_seeded = true;
    }
    Ok(rep)
}

/// Make the store's WAN/LAN/OPT roles exactly those of `b` (the console menu's
/// "Assign interfaces" after the first boot, `patronus interfaces assign`).
/// Every named interface must exist and carry one role; there must be a WAN.
/// Interfaces that had a role and are not named lose it. A config revision
/// is kept first so the change can be rolled back. Returns the new roles.
pub async fn reassign_roles(
    store: &ConfigStore,
    b: &Bootstrap,
    existing: &[String],
    actor: &str,
) -> Result<Vec<(String, String)>> {
    let roles = b.roles();
    if b.wan.is_empty() {
        return Err(Error::Config("no WAN interface given".into()));
    }
    let mut seen = std::collections::HashSet::new();
    for (n, role) in &roles {
        if !existing.contains(n) {
            return Err(Error::Config(format!(
                "{} interface {n:?} does not exist (present: {})",
                role.to_uppercase(),
                existing.join(", ")
            )));
        }
        if !seen.insert(n.clone()) {
            return Err(Error::Config(format!("interface {n:?} is given two roles")));
        }
    }
    let old = store.interface_roles().await?;
    if old
        .iter()
        .cloned()
        .collect::<std::collections::BTreeSet<_>>()
        == roles
            .iter()
            .cloned()
            .collect::<std::collections::BTreeSet<_>>()
    {
        return Ok(roles);
    }
    store
        .snapshot(actor, "before interface assignment (console)")
        .await?;
    for (n, _) in old.iter().filter(|(n, _)| !seen.contains(n)) {
        store.set_interface_role(n, None).await?;
    }
    store.set_interface_roles(&roles).await?;
    store
        .audit(
            actor,
            "assign_interfaces",
            "interfaces",
            None,
            &serde_json::json!({"before": old, "after": roles}),
        )
        .await?;
    Ok(roles)
}

/// The default rows (see the module docs).
pub fn default_filter_rules() -> Vec<(FirewallRule, RuleOrigin)> {
    let mut anti = FirewallRule::new(
        "Anti-lockout".into(),
        ChainType::Input,
        FirewallAction::Accept,
    );
    anti.interface_in = Some("@mgmt".into());
    anti.protocol = Some(Protocol::Tcp);
    anti.dport = Some(PortSpec::Multiple(anti_lockout_ports()));
    anti.comment = Some("Anti-lockout: SSH and web UI from LAN (system rule)".into());

    let mut lan_fw = FirewallRule::new(
        "Allow LAN to firewall".into(),
        ChainType::Input,
        FirewallAction::Accept,
    );
    lan_fw.interface_in = Some("@lan".into());
    lan_fw.comment = Some("Default: LAN may reach the firewall itself".into());

    let mut lan_any = FirewallRule::new(
        "Allow LAN to any".into(),
        ChainType::Forward,
        FirewallAction::Accept,
    );
    lan_any.interface_in = Some("@lan".into());
    lan_any.comment = Some("Default: LAN may reach any destination".into());

    vec![
        (anti, RuleOrigin::System),
        (lan_fw, RuleOrigin::Default),
        (lan_any, RuleOrigin::Default),
    ]
}

/// The default NAT rows. Empty: outbound NAT is automatic (the firewall
/// applier generates an IPv4 masquerade for every interface with the WAN
/// role while `firewall.outbound_nat_mode` is `automatic` or `hybrid`, the
/// default), so a WAN added later is covered without a new row.
pub fn default_nat_rules() -> Vec<NatRule> {
    Vec::new()
}

/// Default sysctls (key, value).
pub const DEFAULT_SYSCTLS: &[(&str, &str)] = &[
    ("net.ipv4.ip_forward", "1"),
    ("net.ipv6.conf.all.forwarding", "1"),
];

/// Idempotent: a row that is already there (same name and origin) is not
/// inserted again, so a power cut between seeding and recording
/// [`DEFAULTS_SEEDED_KEY`] does not duplicate the defaults on the next boot.
/// Does the store already hold a rule an operator (or an older release's user) created?
async fn has_user_rules(store: &ConfigStore) -> Result<bool> {
    Ok(store
        .load_firewall_rules_with_origin()
        .await?
        .iter()
        .any(|(_, o)| *o == RuleOrigin::User))
}

async fn seed_default_rules(store: &ConfigStore) -> Result<()> {
    let have: Vec<(String, RuleOrigin)> = store
        .load_firewall_rules_with_origin()
        .await?
        .into_iter()
        .map(|(r, o)| (r.name, o))
        .collect();
    for (rule, origin) in default_filter_rules() {
        if !have.iter().any(|(n, o)| *n == rule.name && *o == origin) {
            store.insert_firewall_rule(&rule, origin).await?;
        }
    }
    seed_nat_rules(store, default_nat_rules()).await?;
    for (k, v) in DEFAULT_SYSCTLS {
        store.set_sysctl(k, v, RuleOrigin::Default).await?;
    }
    tracing::info!("seeded the default ruleset (anti-lockout, LAN->any, outbound NAT, ip_forward)");
    Ok(())
}

/// Insert each default NAT row unless a default row of that name exists
/// (idempotent like the filter rules; a user row of the same name does not
/// count). [`default_nat_rules`] is empty today, so this is exercised by
/// its own test.
async fn seed_nat_rules(store: &ConfigStore, rules: Vec<NatRule>) -> Result<()> {
    let have_nat: Vec<(String, RuleOrigin)> = store
        .load_nat_rules_with_origin()
        .await?
        .into_iter()
        .map(|(r, o)| (r.name, o))
        .collect();
    for rule in rules {
        if !have_nat
            .iter()
            .any(|(n, o)| *n == rule.name && *o == RuleOrigin::Default)
        {
            store.insert_nat_rule(&rule, RuleOrigin::Default).await?;
        }
    }
    Ok(())
}

