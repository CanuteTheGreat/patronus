    #[tokio::test]
    async fn stored_web_port_round_trips_through_export_and_import() {
        let s = ConfigStore::open_in_memory().await.unwrap();
        assert_eq!(stored_web_port(&s).await, None);
        s.save_system_config(WEB_PORT_KEY, "9443").await.unwrap();
        assert_eq!(stored_web_port(&s).await, Some(9443));
        let doc = s.export_json().await.unwrap();
        let t = ConfigStore::open_in_memory().await.unwrap();
        t.import_json(&doc).await.unwrap();
        assert_eq!(stored_web_port(&t).await, Some(9443));
        // an empty value (back to default) and garbage both read as unset
        t.save_system_config(WEB_PORT_KEY, "").await.unwrap();
        assert_eq!(stored_web_port(&t).await, None);
        t.save_system_config(WEB_PORT_KEY, "70000").await.unwrap();
        assert_eq!(stored_web_port(&t).await, None);
    }
