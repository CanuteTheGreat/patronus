//! First-boot defaults: interface roles from `/etc/patronus/patronus.toml`
//! and the safe default ruleset.
//!
//! A fresh Patronus box must route LAN -> WAN and stay manageable without
//! anyone touching the UI first, so on the first `patronus apply` (or the
//! first `patronus-web` start when no boot unit ran, e.g. in a container)
//! the store is seeded with:
//!
//! | rule | origin | what |
//! |---|---|---|
//! | Anti-lockout | system | input, `@mgmt`, tcp 22 + 8443 accept (follows `ssh.port` and the web port `web.https_port`, see [`follow_ports`]) |
//! | Allow LAN to firewall | default | input, `@lan` accept |
//! | Allow LAN to any | default | forward, `@lan` accept |
//! | Outbound NAT | automatic | IPv4 masquerade on every WAN interface (generated by the firewall applier, `firewall.outbound_nat_mode`) |
//! | ip_forward v4/v6 | default | `net.ipv4.ip_forward=1`, `net.ipv6.conf.all.forwarding=1` |
//!
//! Everything else -- in particular anything arriving on the WAN -- hits
//! the base ruleset's `policy drop`. Defaults are seeded once (deleting
//! one is respected on the next boot); the anti-lockout rule is a system
//! rule that the API refuses to delete.
//!
//! `@mgmt` is resolved by the firewall applier to the LAN interfaces, or to
//! the WAN if there is no LAN (single-NIC box, like pfSense), or to every
//! interface if no role is assigned at all -- so the box can always be
//! reached to finish setting it up.

use crate::store::{ConfigStore, RuleOrigin};
use patronus_core::types::{ChainType, FirewallAction, FirewallRule, NatRule, PortSpec, Protocol};
use patronus_core::{Error, Result};
use std::path::{Path, PathBuf};

/// Installed bootstrap file (written by the installer / catalyst ISO).
pub const DEFAULT_BOOTSTRAP_PATH: &str = "/etc/patronus/patronus.toml";

/// `system_config` key recording that the defaults were seeded.
pub const DEFAULTS_SEEDED_KEY: &str = "defaults_seeded_at";

/// The SSH port when `ssh.port` is not set.
pub const DEFAULT_SSH_PORT: u16 = 22;

/// The web UI's HTTPS port when neither `$PATRONUS_HTTPS_PORT` nor `web.https_port` is set.
pub const DEFAULT_WEB_PORT: u16 = 8443;

/// Ports the anti-lockout rule is SEEDED with (SSH and the web UI at their
/// defaults). The rule that is rendered follows the configured ports, see
/// [`follow_ports`]; this list is only the stored starting point.
pub const ANTI_LOCKOUT_PORTS: &[u16] = &[DEFAULT_SSH_PORT, DEFAULT_WEB_PORT];

/// Ports the anti-lockout rule opens at first-boot seeding: [`ANTI_LOCKOUT_PORTS`],
/// or `$PATRONUS_ANTI_LOCKOUT_PORTS` (comma list) when set. The router image sets
/// it to `22,80,443` because its web UI listens on 443 (+ the 80 redirect).
pub fn anti_lockout_ports() -> Vec<u16> {
    std::env::var("PATRONUS_ANTI_LOCKOUT_PORTS")
        .ok()
        .map(|v| {
            v.split(',')
                .filter_map(|p| p.trim().parse::<u16>().ok())
                .collect::<Vec<_>>()
        })
        .filter(|v| !v.is_empty())
        .unwrap_or_else(|| ANTI_LOCKOUT_PORTS.to_vec())
}

/// `system_config` key of the managed SSH server's port (lane H/L3).
pub const SSH_PORT_KEY: &str = "ssh.port";

/// `system_config` key of the web UI's HTTPS port (System page, API
/// `/api/system/web`, declarative export). Empty/absent = not configured.
pub const WEB_PORT_KEY: &str = "web.https_port";

/// Environment override of the web UI's HTTPS port. It wins over the stored
/// key; the embedded router image sets it to 443. The firewall applier reads
/// it too, so a process that applies the firewall without it in its
/// environment (applyd) sees only the stored key.
pub const WEB_PORT_ENV: &str = "PATRONUS_HTTPS_PORT";

/// A usable TCP port (1-65535).
pub fn parse_port(v: &str) -> Option<u16> {
    v.trim().parse::<u16>().ok().filter(|p| *p != 0)
}

/// The SSH port the anti-lockout rule must keep open (`ssh.port`, default 22).
pub async fn ssh_port(store: &ConfigStore) -> u16 {
    store
        .load_system_config(SSH_PORT_KEY)
        .await
        .ok()
        .flatten()
        .and_then(|v| parse_port(&v))
        .unwrap_or(DEFAULT_SSH_PORT)
}

/// The web port stored in `web.https_port`, if one is set.
pub async fn stored_web_port(store: &ConfigStore) -> Option<u16> {
    store
        .load_system_config(WEB_PORT_KEY)
        .await
        .ok()
        .flatten()
        .and_then(|v| parse_port(&v))
}

/// The web port someone configured: `$PATRONUS_HTTPS_PORT`, else the stored
/// key; `None` when neither is set.
pub async fn configured_web_port(store: &ConfigStore) -> Option<u16> {
    pick_web_port(
        std::env::var(WEB_PORT_ENV).ok().as_deref(),
        stored_web_port(store).await,
    )
}

/// Precedence of the web port: a valid environment value, else the stored one.
pub fn pick_web_port(env: Option<&str>, stored: Option<u16>) -> Option<u16> {
    env.and_then(parse_port).or(stored)
}

/// The port patronus-web listens on: [`configured_web_port`], else 8443.
pub async fn web_port(store: &ConfigStore) -> u16 {
    configured_web_port(store).await.unwrap_or(DEFAULT_WEB_PORT)
}

/// Make the system "Anti-lockout" rule open the ports the box really
/// uses. The stored rule carries the seeded defaults (tcp/22, tcp/8443):
///
/// * `ssh_port` (`ssh.port`) replaces tcp/22;
/// * `web_port` (the configured web UI port, `None` = not configured) replaces
///   the seeded tcp/8443 and is added when the stored list does not name it
///   (the router image seeds 22,80,443).
///
/// Nothing is stored: the rule follows the settings on every apply, so
/// changing a port can never strand the management session.
pub fn follow_ports(
    rule: &mut FirewallRule,
    origin: RuleOrigin,
    ssh_port: u16,
    web_port: Option<u16>,
) {
    if origin != RuleOrigin::System || rule.name != "Anti-lockout" {
        return;
    }
    let Some(PortSpec::Multiple(ports)) = &mut rule.dport else {
        return;
    };
    if let Some(w) = web_port {
        if w != DEFAULT_WEB_PORT {
            ports.retain(|p| *p != DEFAULT_WEB_PORT);
        }
        if !ports.contains(&w) {
            ports.push(w);
        }
    }
    if ssh_port != DEFAULT_SSH_PORT {
        ports.retain(|p| *p != DEFAULT_SSH_PORT && *p != ssh_port);
        ports.insert(0, ssh_port);
    }
}

/// The bootstrap file path: `$PATRONUS_BOOTSTRAP` or the default.
pub fn default_bootstrap_path() -> PathBuf {
    std::env::var_os("PATRONUS_BOOTSTRAP")
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(DEFAULT_BOOTSTRAP_PATH))
}

/// Interface roles read from the `[network]` section of patronus.toml.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Bootstrap {
    pub wan: Vec<String>,
    pub lan: Vec<String>,
}

#[derive(serde::Deserialize, Default)]
struct BootstrapFile {
    #[serde(default)]
    network: NetworkSection,
}

#[derive(serde::Deserialize, Default)]
struct NetworkSection {
    wan_interface: Option<String>,
    lan_interface: Option<String>,
    #[serde(default)]
    wan_interfaces: Vec<String>,
    #[serde(default)]
    lan_interfaces: Vec<String>,
}

impl Bootstrap {
    /// Parse patronus.toml text.
    pub fn parse(text: &str) -> Result<Self> {
        let f: BootstrapFile =
            toml::from_str(text).map_err(|e| Error::Config(format!("patronus.toml: {e}")))?;
        let mut b = Bootstrap {
            wan: f.network.wan_interfaces,
            lan: f.network.lan_interfaces,
        };
        if let Some(w) = f.network.wan_interface {
            b.wan.insert(0, w);
        }
        if let Some(l) = f.network.lan_interface {
            b.lan.insert(0, l);
        }
        b.wan.retain(|s| !s.trim().is_empty());
        b.lan.retain(|s| !s.trim().is_empty());
        b.wan.dedup();
        b.lan.dedup();
        Ok(b)
    }

    /// Load the bootstrap file; `Ok(None)` if it does not exist.
    pub fn load(path: &Path) -> Result<Option<Self>> {
        match std::fs::read_to_string(path) {
            Ok(t) => Self::parse(&t).map(Some),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(Error::Config(format!("read {}: {e}", path.display()))),
        }
    }
}

/// Network interfaces present in the current network namespace
/// (`/sys/class/net`, which `ip netns exec` remounts per namespace).
pub fn existing_interfaces() -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir("/sys/class/net")
        .map(|d| {
            d.filter_map(|e| e.ok())
                .map(|e| e.file_name().to_string_lossy().to_string())
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

/// What [`ensure_defaults`] changed.
#[derive(Debug, Default, Clone, serde::Serialize)]
pub struct SeedReport {
    pub roles_assigned: Vec<(String, String)>,
    pub defaults_seeded: bool,
    pub warnings: Vec<String>,
}

/// Assign interface roles from the bootstrap file (only while the store has
/// no roles at all -- once roles exist the store wins) and seed the default
/// ruleset once. Safe to call at every boot.
pub async fn ensure_defaults(
    store: &ConfigStore,
    bootstrap: Option<&Bootstrap>,
    existing: &[String],
) -> Result<SeedReport> {
    let mut rep = SeedReport::default();

    if store.interface_roles().await?.is_empty() {
        if let Some(b) = bootstrap {
            for (role, names) in [("wan", &b.wan), ("lan", &b.lan)] {
                for n in names {
                    if existing.iter().any(|e| e == n) {
                        store.set_interface_role(n, Some(role)).await?;
                        rep.roles_assigned.push((n.clone(), role.to_string()));
                    } else {
                        let w = format!(
                            "patronus.toml names {role} interface {n:?}, which does not exist \
                             (present: {}); not assigned",
                            existing.join(", ")
                        );
                        tracing::warn!("{w}");
                        rep.warnings.push(w);
                    }
                }
            }
        }
        if store.interface_roles().await?.is_empty() {
            let w = "no interface has a WAN/LAN role: management access (anti-lockout) is \
                     open on every interface and nothing is forwarded until roles are \
                     assigned ([network] in patronus.toml, or the Interfaces page)"
                .to_string();
            tracing::warn!("{w}");
            rep.warnings.push(w);
        }
    }

    if store
        .load_system_config(DEFAULTS_SEEDED_KEY)
        .await?
        .is_none()
    {
        // A store that carries rules somebody wrote is an upgrade, even when it is so old that
        // it has no "seeded" marker (the v0.1.0 layout): it must not get new behaviour.
        let upgraded = has_user_rules(store).await?;
        seed_default_rules(store).await?;
        // DNS rebinding protection is on for a new install; a store that
        // predates the setting keeps it off (split-horizon names would break)
        if !upgraded {
            sqlx::query(
                "INSERT OR IGNORE INTO lan_settings (key, value, updated_at) VALUES ('dns.rebind_protection', '1', ?)",
            )
            .bind(chrono::Utc::now().timestamp())
            .execute(store.pool()?)
            .await
            .map_err(|e| {
                patronus_core::Error::Config(format!("seed DNS rebind protection: {e}"))
            })?;
        }
        store
            .save_system_config(DEFAULTS_SEEDED_KEY, &chrono::Utc::now().to_rfc3339())
            .await?;
        store
            .audit(
                "system",
                "seed_defaults",
                "config",
                None,
                &serde_json::json!({"roles": rep.roles_assigned}),
            )
            .await?;
        rep.defaults_seeded = true;
    }
    Ok(rep)
}

/// The default rows (see the module docs).
pub fn default_filter_rules() -> Vec<(FirewallRule, RuleOrigin)> {
    let mut anti = FirewallRule::new(
        "Anti-lockout".into(),
        ChainType::Input,
        FirewallAction::Accept,
    );
    anti.interface_in = Some("@mgmt".into());
    anti.protocol = Some(Protocol::Tcp);
    anti.dport = Some(PortSpec::Multiple(anti_lockout_ports()));
    anti.comment = Some("Anti-lockout: SSH and web UI from LAN (system rule)".into());

    let mut lan_fw = FirewallRule::new(
        "Allow LAN to firewall".into(),
        ChainType::Input,
        FirewallAction::Accept,
    );
    lan_fw.interface_in = Some("@lan".into());
    lan_fw.comment = Some("Default: LAN may reach the firewall itself".into());

    let mut lan_any = FirewallRule::new(
        "Allow LAN to any".into(),
        ChainType::Forward,
        FirewallAction::Accept,
    );
    lan_any.interface_in = Some("@lan".into());
    lan_any.comment = Some("Default: LAN may reach any destination".into());

    vec![
        (anti, RuleOrigin::System),
        (lan_fw, RuleOrigin::Default),
        (lan_any, RuleOrigin::Default),
    ]
}

/// The default NAT rows. Empty: outbound NAT is automatic (the firewall
/// applier generates an IPv4 masquerade for every interface with the WAN
/// role while `firewall.outbound_nat_mode` is `automatic` or `hybrid`, the
/// default), so a WAN added later is covered without a new row.
pub fn default_nat_rules() -> Vec<NatRule> {
    Vec::new()
}

/// Default sysctls (key, value).
pub const DEFAULT_SYSCTLS: &[(&str, &str)] = &[
    ("net.ipv4.ip_forward", "1"),
    ("net.ipv6.conf.all.forwarding", "1"),
];

/// Idempotent: a row that is already there (same name and origin) is not
/// inserted again, so a power cut between seeding and recording
/// [`DEFAULTS_SEEDED_KEY`] does not duplicate the defaults on the next boot.
/// Does the store already hold a rule an operator (or an older release's user) created?
async fn has_user_rules(store: &ConfigStore) -> Result<bool> {
    Ok(store
        .load_firewall_rules_with_origin()
        .await?
        .iter()
        .any(|(_, o)| *o == RuleOrigin::User))
}

async fn seed_default_rules(store: &ConfigStore) -> Result<()> {
    let have: Vec<(String, RuleOrigin)> = store
        .load_firewall_rules_with_origin()
        .await?
        .into_iter()
        .map(|(r, o)| (r.name, o))
        .collect();
    for (rule, origin) in default_filter_rules() {
        if !have.iter().any(|(n, o)| *n == rule.name && *o == origin) {
            store.insert_firewall_rule(&rule, origin).await?;
        }
    }
    seed_nat_rules(store, default_nat_rules()).await?;
    for (k, v) in DEFAULT_SYSCTLS {
        store.set_sysctl(k, v, RuleOrigin::Default).await?;
    }
    tracing::info!("seeded the default ruleset (anti-lockout, LAN->any, outbound NAT, ip_forward)");
    Ok(())
}

/// Insert each default NAT row unless a default row of that name exists
/// (idempotent like the filter rules; a user row of the same name does not
/// count). [`default_nat_rules`] is empty today, so this is exercised by
/// its own test.
async fn seed_nat_rules(store: &ConfigStore, rules: Vec<NatRule>) -> Result<()> {
    let have_nat: Vec<(String, RuleOrigin)> = store
        .load_nat_rules_with_origin()
        .await?
        .into_iter()
        .map(|(r, o)| (r.name, o))
        .collect();
    for rule in rules {
        if !have_nat
            .iter()
            .any(|(n, o)| *n == rule.name && *o == RuleOrigin::Default)
        {
            store.insert_nat_rule(&rule, RuleOrigin::Default).await?;
        }
    }
    Ok(())
}

